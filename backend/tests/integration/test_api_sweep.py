"""Every API endpoint, checked automatically against a sample estate (Azure, AWS, GCP).

1. Signed-in administrator: no endpoint returns a server error (5xx). GET endpoints with no path parameters must succeed
   (2xx) unless a documented, legitimate 4xx applies (feature switched off, external service not configured).
2. Anonymous caller: every non-public endpoint refuses (401 / 403).
3. Unknown IDs and invalid bodies: handled with a clean 4xx, never a crash.
4. Read-only roles cannot call write endpoints (403).

The report of every call is written to docs/review/api-sweep-report.md so the result is reviewable evidence."""
from __future__ import annotations

import re
from pathlib import Path

import pytest

from tests.conftest import use_settings
from tests.integration.sample_estate import seed
from tests.integration.test_identity_governance import login

H = {"X-Requested-With": "mcp-dashboard"}
PUBLIC = ("/health", "/health/ready", "/api/v1/auth/login", "/api/v1/auth/callback", "/api/v1/auth/config", "/api/v1/auth/me",
          "/api/v1/auth/logout", "/api/v1/auth/dev-login",
          "/api/v1/events/pubsub")  # Pub/Sub: Google push with its own OIDC token check (tests/security)
REPORT = Path(__file__).resolve().parents[3] / "docs" / "review" / "api-sweep-report.md"
# endpoints that legitimately answer 4xx in a test environment, with the reason (checked to be 4xx, not 5xx)
EXPECTED_4XX = {
    "/api/v1/ai/": "AI provider not configured in tests (AI_PROVIDER=none): clear 4xx/503 message, no fabricated answer",
    "/api/v1/sheets": "Google Sheets not configured in tests",
}


def _routes(client):
    spec = client.app_ref.openapi()
    return [(m.upper(), p, op) for p, ops in spec["paths"].items() for m, op in ops.items()]


def _fill(path: str) -> str:
    return re.sub(r"\{[^}]+\}", "999999", path)


@pytest.fixture()
def estate(client, db):
    seed(db)
    db.commit()
    login(client, db, "admin@latentview.com", "admin")
    return client


def test_every_endpoint_admin_no_server_errors(estate, db):
    client = estate
    rows, failures = [], []
    for method, path, _op in sorted(_routes(client), key=lambda r: (r[1], r[0])):
        if path in PUBLIC or "stream" in path:  # SSE stream is tested separately (long-lived connection)
            continue
        url = _fill(path)
        has_params = "{" in path
        if method == "GET":
            r = client.get(url, params={"format": "csv"} if "export" in path or "download" in path else None)
        else:
            r = client.request(method, url, json={}, headers=H)  # empty body: must be a 4xx validation answer, never 5xx
        ok = r.status_code < 500
        if method == "GET" and not has_params and not (200 <= r.status_code < 300):
            ok = ok and any(path.startswith(k) for k in EXPECTED_4XX) or r.status_code in (400, 404, 409, 422, 503)
        rows.append((method, path, r.status_code, "PASS" if ok else "FAIL"))
        if not ok:
            failures.append(f"{method} {path} -> {r.status_code}: {r.text[:200]}")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("# API sweep report (generated by tests/integration/test_api_sweep.py)\n\n"
                      f"Endpoints called as administrator: {len(rows)}; failed: {len(failures)}\n\n"
                      "| Method | Path | Status | Result |\n|---|---|---|---|\n" +
                      "\n".join(f"| {m} | `{p}` | {s} | {v} |" for m, p, s, v in rows) + "\n", encoding="utf-8")
    assert not failures, "\n".join(failures)


def test_anonymous_is_refused_everywhere(client):
    use_settings(client, auth_mode="google", google_oauth_client_id="c", google_oauth_client_secret="x",
                 google_allowed_domain="latentview.com", secret_key="k" * 40)
    open_ = []
    for method, path, _ in _routes(client):
        if path in PUBLIC or path.startswith("/api/v1/auth"):
            continue
        r = client.request(method, _fill(path), json={} if method != "GET" else None, headers=H)
        if r.status_code not in (401, 403):
            open_.append(f"{method} {path} -> {r.status_code}")
    assert not open_, "endpoints reachable without signing in:\n" + "\n".join(open_)


def test_read_only_role_cannot_write(estate, db):
    client = estate
    login(client, db, "viewer@latentview.com", "executive")
    allowed = []
    for method, path, _ in _routes(client):
        if method == "GET" or path in PUBLIC or path.startswith("/api/v1/auth"):
            continue
        r = client.request(method, _fill(path), json={}, headers=H)
        if r.status_code < 400 or r.status_code >= 500:
            allowed.append(f"{method} {path} -> {r.status_code}")
    # executives may record management decisions and use the assistant; everything else must be refused
    unexpected = [a for a in allowed if "/decisions" not in a and "/ai/" not in a and "/assistant" not in a]
    assert not unexpected, "\n".join(unexpected)


def test_resources_without_a_state_are_counted_everywhere(estate, db):
    """Regression: `state != 'deleted'` dropped rows whose state is NULL, so the Executive page showed 0 resources while
    Cloud accounts showed them. Every view must count the same resources."""
    from sqlalchemy import func, select

    from app.models import CloudResource
    client = estate
    total = db.scalar(select(func.count()).select_from(CloudResource))
    assert total and db.scalar(select(func.count()).select_from(CloudResource).where(CloudResource.state.is_(None))) == total
    cc = {k["key"]: k for k in client.get("/api/v1/executive/summary").json()["kpis"]}
    assert cc["resources"]["value"] == total
    home = client.get("/api/v1/home").json()
    assert sum(c["resources"] for c in home["clouds"].values()) == total
    tree = client.get("/api/v1/accounts/tree").json()
    assert sum(c["resources"] for c in tree["clouds"]) == total
